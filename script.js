function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, char => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  })[char]);
}

function loadFrndzoneState() {
  const saved = localStorage.getItem('clubflow-frndzone');
  if (!saved) return;

  try {
    const parsed = JSON.parse(saved);
    if (!parsed || typeof parsed !== 'object') {
      throw new Error('Saved Frndzone data must be an object.');
    }

    ['members', 'tasks', 'messages', 'announcements', 'agentAlerts'].forEach(key => {
      if (Array.isArray(parsed[key])) frndzoneState[key] = parsed[key];
    });
    if (typeof parsed.leaderBusy === 'boolean') frndzoneState.leaderBusy = parsed.leaderBusy;
    if (typeof parsed.agentStatus === 'string') frndzoneState.agentStatus = parsed.agentStatus;
  } catch (error) {
    console.error('Unable to load saved Frndzone data:', error);
  }
}

function saveFrndzoneState() {
  localStorage.setItem('clubflow-frndzone', JSON.stringify(frndzoneState));
}

