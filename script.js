// UNIFIED EXECUTION HANDLER (Fires Gmail, Calendar, and Supabase mutations simultaneously)
function executeUnifiedCrisisResolution() {
  const pkg = crisisPackages[state.activeCrisisKey];
  if (!pkg || pkg.executed) return;

  // Save any inline edits made by coordinator in the browser
  pkg.draftAttendee = document.getElementById('draftAttendeeTextarea').value;
  pkg.draftExec = document.getElementById('draftExecTextarea').value;
  pkg.executed = true;

  // 1. Mutate Calendar State ([CANCELED] & free time block)
  const targetEventId = state.activeCrisisKey === 'speaker' ? 'evt_speaker' : 'evt_venue';
  const calEvent = state.events.find(e => e.id === targetEventId);
  if (calEvent) {
    calEvent.canceled = true;
  }

  // 2. Inject High-Priority Tasks into Supabase Task View
  pkg.stagedTasks.forEach((st, idx) => {
    state.totalTasks += 1;
    state.tasks.unshift({
      id: Date.now() + idx,
      title: st.title,
      category: st.category,
      status: 'Pending'
    });
  });

  // 3. Log in Recent Activity & Supabase Audit Trail
  state.recentActivities.unshift({
    id: Date.now(),
    title: `Crisis Resolution Executed: ${pkg.calTitle} [CANCELED]`,
    subtitle: 'Unified Execution (Gmail + Calendar + Supabase) · Just now',
    badge: 'Resolved',
    targetTab: 'calendar',
    iconType: 'green'
  });

  addAuditLog('unified.execute', `Fired Gmail broadcast, Calendar [CANCELED] & 2 Supabase tasks for "${pkg.calTitle}"`);

  // Hide overview banner if all crises resolved
  if (crisisPackages.speaker.executed && crisisPackages.venue.executed) {
    const banner = document.getElementById('overviewCrisisBanner');
    if (banner) banner.style.display = 'none';
  }

  updateKPIs();
  renderCrisisDiffDashboard();
  renderRecentActivity();
  renderTasks();
  renderCalendar();
  showToast('⚡ Unified Resolution Executed! Gmail sent, Calendar updated & Supabase tasks injected.');
}

