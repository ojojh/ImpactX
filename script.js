function monitorFrndzoneDeadlines() {
  const now = new Date();
  const soon = new Date(now.getTime() + 48 * 60 * 60 * 1000);
  const previousStatus = frndzoneState.agentStatus;
  const previousAlerts = JSON.stringify(frndzoneState.agentAlerts);
  const dueSoon = frndzoneState.tasks.filter(task => {
    if (task.completed) return false;
    const dueAt = new Date(`${task.dueDate}T23:59:59`);
    return !Number.isNaN(dueAt.getTime()) && dueAt <= soon;
  });

  frndzoneState.agentAlerts = [];
  if (!dueSoon.length) {
    frndzoneState.agentStatus = 'No open tasks are due within the next 48 hours. The circle is on track.';
  } else if (!frndzoneState.leaderBusy) {
    frndzoneState.agentStatus = `${dueSoon.length} open ${dueSoon.length === 1 ? 'task is' : 'tasks are'} due within 48 hours. The leader is available; no handoff is needed yet.`;
  } else {
    const helpers = frndzoneState.members.filter(member => member.id !== 'leader' && member.status === 'In circle');
    if (!helpers.length) {
      frndzoneState.agentStatus = 'Deadlines need attention, but there are no other active circle members to prompt. Invite a friend to share the workload.';
    } else {
      dueSoon.forEach((task, index) => {
        const preferredHelper = helpers.find(member => member.id !== task.assignedTo);
        const helper = preferredHelper || helpers[index % helpers.length];
        frndzoneState.agentAlerts.push({
          taskId: task.id,
          taskTitle: task.title,
          dueDate: task.dueDate,
          memberName: helper.name
        });
      });
      frndzoneState.agentStatus = `Leader is busy. Frndzone found ${dueSoon.length} deadline${dueSoon.length === 1 ? '' : 's'} due within 48 hours and prepared teammate handoff suggestions.`;
      if (previousStatus !== frndzoneState.agentStatus || previousAlerts !== JSON.stringify(frndzoneState.agentAlerts)) {
        frndzoneState.messages.push({
          id: `frnd-agent-${Date.now()}`,
          author: 'Frndzone agent',
          text: `Deadline check: ${frndzoneState.agentAlerts.map(alert => `${alert.memberName} can help with "${alert.taskTitle}"`).join('; ')}.`
        });
      }
    }
  }

  saveFrndzoneState();
  renderFrndzone();
  showToast('Frndzone deadline check complete.');
}

